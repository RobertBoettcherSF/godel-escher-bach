const LANG_KEY = "geb.lang";
const HTML_LANG = {en: "en-GB", de: "de", es: "es", fr: "fr"};
let current = "en";

export function t(key) {
  const pack = STRINGS[current] || STRINGS.en;
  return pack[key] ?? STRINGS.en[key] ?? key;
}

export function getLang() {
  try {
    const saved = globalThis.localStorage?.getItem(LANG_KEY);
    if (saved && STRINGS[saved]) return saved;
  } catch {
    /* private mode */
  }
  return "en";
}

export function applyLanguage(lang) {
  current = STRINGS[lang] ? lang : "en";
  if (typeof document === "undefined") return;
  document.documentElement.lang = HTML_LANG[current];
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    node.setAttribute("aria-label", t(node.dataset.i18nAria));
  });
  const titleKey = document.body?.dataset.pageTitle;
  if (titleKey) document.title = t(titleKey);
  document.querySelectorAll("[data-language]").forEach((button) => {
    const on = button.dataset.language === current;
    button.setAttribute("aria-pressed", String(on));
  });
  window.dispatchEvent(new CustomEvent("languagechange"));
}

export function setLang(lang) {
  const code = STRINGS[lang] ? lang : "en";
  try {
    globalThis.localStorage?.setItem(LANG_KEY, code);
  } catch {
    /* ignore */
  }
  applyLanguage(code);
}

export {STRINGS};
